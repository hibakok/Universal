#!/usr/bin/env python3
"""pegen_v2_code.py — ЛИСТИНГ ветви v2 pegen.exe (E9.4-4b-4; LAB/ai).

Список инструкций всех кирпичей v2 (K0-Q012..Q019, K0-E005..E007,
K0-G043) для pegen_build_v2.py: функции build_v2_code(syms) — сборка
Asm-объекта. Кодировки — мини-ассемблер pegen_v2_asm.py (принцип e4_ledger:
ручные формы, компоновка лишь разрешает rip-смещения/длины переходов).
Раздел на два файла — лимит методологии 500 строк.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from pegen_v2_asm import Asm                # noqa: E402

OUTLIM = 0x40000               # вместимость outbuf (предел инструмента)
SPANMAX = 64                    # предел !hdr-патчей (спан-таблица)
SECMAX = 128                    # предел !sec-записей (таблица)
SECLEN = 0x2000                 # буфер сек-данных (128 x 64 Б)


def build_v2_code(syms):
    """Список инструкций ветви v2 (все кирпичи; syms — данные/сдвиги)."""
    A = Asm()
    A.syms = syms

    # ---------------------------------------------- K0-Q012 sniff_v2
    A.label("sniff_v2")
    A.lea_rip("rsi", "filebuf", "Q012 lea rsi,[rip+filebuf] (сентинел)")
    A.mov_rip("eax", "pegsize", "Q012 mov eax,[rip+pegsize]", w=0)
    A.cdqe("Q012 cdqe")
    A.lea_rip("rcx", "filebuf", "Q012 lea rcx,[rip+filebuf]")
    A.alu_rr("add", "rcx", "rax", "Q012 add rcx,rax (конец текста)")
    A.movb_ri("rcx", None, 0, "Q012 mov byte [rcx],0 (сентинел NUL)")
    A.label("sv_next")
    A.movzx("eax", "rsi", None, "Q012 movzx eax,byte [rsi]")
    A.test_rr("eax", "eax", "Q012 test al,al", w=0)
    A.jcc("e", "sv_v1", "Q012 jz sv_v1 (конец текста — путь v1)")
    A.cmp_ri8("al", 0x3B, "Q012 cmp al,';'")
    A.jcc("e", "sv_skipline", "Q012 jz sv_skipline")
    A.cmp_ri8("al", 0x0D, "Q012 cmp al,0x0D")
    A.jcc("e", "sv_skipline", "Q012 jz sv_skipline")
    A.cmp_ri8("al", 0x0A, "Q012 cmp al,0x0A")
    A.jcc("e", "sv_lf", "Q012 jz sv_lf")
    A.cmp_ri8("al", 0x20, "Q012 cmp al,' '")
    A.jcc("e", "sv_adv", "Q012 jz sv_adv")
    A.cmp_ri8("al", 9, "Q012 cmp al,9 (таб)")
    A.jcc("e", "sv_adv", "Q012 jz sv_adv")
    A.cmp_ri8("al", 0x21, "Q012 cmp al,'!'")
    A.jcc("e", "sv_dir", "Q012 jz sv_dir (директива)")
    A.jmp("sv_v1", "Q012 jmp sv_v1 (не '!' — v1: parse_peg отвергнет)")
    A.label("sv_adv")
    A.inc("rsi", "Q012 inc rsi", w=1)
    A.jmp("sv_next", "Q012 jmp sv_next")
    A.label("sv_lf")
    A.inc("rsi", "Q012 inc rsi (конец строки)", w=1)
    A.jmp("sv_next", "Q012 jmp sv_next")
    A.label("sv_dir")
    A.inc("rsi", "Q012 inc rsi (пропуск '!')", w=1)
    A.call("match_kw2", "Q012 call match_kw2 (первая директива)")
    A.alu_ri("cmp", "rax", -1, "Q012 cmp rax,-1")
    A.jcc("e", "sv_v1", "Q012 jz sv_v1 (слово не из v2 — путь v1)")
    A.test_rr("eax", "eax", "Q012 test eax,eax", w=0)
    A.jcc("e", "sv_v2", "Q012 jz sv_v2 (индекс 0 == pev2)")
    A.jmp("sv_v1", "Q012 jmp sv_v1 (не pev2 первыми — путь v1)")
    A.label("sv_v2")
    A.call("wrap2_main", "Q012 call wrap2_main (v2 — не возвращает)")
    A.label("sv_v1")
    A.call("parse_peg", "Q012 call parse_peg (v1)")
    A.ret("Q012 ret (rax — от parse_peg)")
    A.label("sv_skipline")
    A.movzx("eax", "rsi", None, "Q012 movzx eax,byte [rsi]")
    A.test_rr("eax", "eax", "Q012 test al,al", w=0)
    A.jcc("e", "sv_v1", "Q012 jz sv_v1")
    A.cmp_ri8("al", 0x0A, "Q012 cmp al,0x0A")
    A.jcc("e", "sv_lf", "Q012 jz sv_lf")
    A.inc("rsi", "Q012 inc rsi", w=1)
    A.jmp("sv_skipline", "Q012 jmp sv_skipline")

    # ---------------------------------------------- K0-Q013 match_kw2
    A.label("match_kw2")
    A.mov_rr("r10", "rsi", "Q013 mov r10,rsi (старт слова)")
    A.lea_rip("r11", "v2kwtab", "Q013 lea r11,[rip+v2kwtab]")
    A.alu_rr("xor", "r9d", "r9d", "Q013 xor r9d,r9d (индекс)", w=0)
    A.label("mk2_loop")
    A.mov_mr("r8", "r11", None, "Q013 mov r8,[r11] (RVA слова)")
    A.alu_rr("add", "r8", "rbx", "Q013 add r8,rbx (адрес слова)")
    A.label("mk2_cmp")
    A.movzx("ecx", "r8", None, "Q013 movzx ecx,byte [r8] (эталон)")
    A.test_rr("ecx", "ecx", "Q013 test cl,cl", w=0)
    A.jcc("e", "mk2_bound", "Q013 jz mk2_bound (конец эталона)")
    A.movzx("eax", "rsi", None, "Q013 movzx eax,byte [rsi] (текст)")
    A.alu_rr("cmp", "eax", "ecx", "Q013 cmp al,cl", w=0)
    A.jcc("ne", "mk2_next", "Q013 jnz mk2_next (промах)")
    A.inc("r8", "Q013 inc r8", w=1)
    A.inc("rsi", "Q013 inc rsi", w=1)
    A.jmp("mk2_cmp", "Q013 jmp mk2_cmp")
    A.label("mk2_bound")
    A.movzx("eax", "rsi", None, "Q013 movzx eax,byte [rsi] (граница)")
    A.cmp_ri8("al", 0x20, "Q013 cmp al,' '")
    A.jcc("e", "mk2_hit", "Q013 jz mk2_hit")
    A.cmp_ri8("al", 9, "Q013 cmp al,9")
    A.jcc("e", "mk2_hit", "Q013 jz mk2_hit")
    A.cmp_ri8("al", 0x0D, "Q013 cmp al,0x0D")
    A.jcc("e", "mk2_hit", "Q013 jz mk2_hit")
    A.cmp_ri8("al", 0x0A, "Q013 cmp al,0x0A")
    A.jcc("e", "mk2_hit", "Q013 jz mk2_hit")
    A.cmp_ri8("al", 0x3B, "Q013 cmp al,';'")
    A.jcc("e", "mk2_hit", "Q013 jz mk2_hit")
    A.test_rr("eax", "eax", "Q013 test al,al", w=0)
    A.jcc("e", "mk2_hit", "Q013 jz mk2_hit (NUL)")
    A.jmp("mk2_next", "Q013 jmp mk2_next (нет границы)")
    A.label("mk2_hit")
    A.mov_rr("eax", "r9d", "Q013 mov eax,r9d (индекс)", w=0)
    A.ret("Q013 ret")
    A.label("mk2_next")
    A.mov_rr("rsi", "r10", "Q013 mov rsi,r10 (вернуть курсор)")
    A.alu_ri("add", "r11", 8, "Q013 add r11,8", w=1)
    A.inc("r9d", "Q013 inc r9d", w=0)
    A.alu_ri("cmp", "r9d", 4, "Q013 cmp r9d,4")
    A.jcc("b", "mk2_loop", "Q013 jb mk2_loop")
    A.mov_ri("rax", -1, "Q013 mov rax,-1 (не найдено)")
    A.ret("Q013 ret")

    # ---------------------------------------------- K0-Q014 hex_blob
    A.label("hex_blob")
    A.alu_rr("xor", "r9d", "r9d", "Q014 xor r9d,r9d (счётчик байтов)", w=0)
    A.label("hb_pair")
    A.alu_rr("cmp", "rdi", "r8", "Q014 cmp rdi,r8 (предел записи)")
    A.jcc("ae", "hb_bad", "Q014 jae hb_bad (за пределом)")
    A.movzx("eax", "rsi", None, "Q014 movzx eax,byte [rsi] (цифра 1)")
    A.call("hex_digit", "Q014 call hex_digit")
    A.alu_ri("cmp", "rax", -1, "Q014 cmp rax,-1")
    A.jcc("e", "hb_end", "Q014 jz hb_end (не hex — конец блоба)")
    A.mov_rr("r11", "rax", "Q014 mov r11,rax (старший полубайт)")
    A.movzx("eax", "rsi", 1, "Q014 movzx eax,byte [rsi+1] (цифра 2)")
    A.call("hex_digit", "Q014 call hex_digit")
    A.alu_ri("cmp", "rax", -1, "Q014 cmp rax,-1")
    A.jcc("e", "hb_bad", "Q014 jz hb_bad (нечётное число цифр)")
    A.shl_ri("r11d", 4, "Q014 shl r11d,4")
    A.alu_rr("add", "r11d", "eax", "Q014 add r11d,eax (байт)", w=0)
    A.mov_rm("rdi", None, "r11b", "Q014 mov [rdi],r11b", w=0, byte=True)
    A.inc("rdi", "Q014 inc rdi", w=1)
    A.alu_ri("add", "rsi", 2, "Q014 add rsi,2", w=1)
    A.inc("r9d", "Q014 inc r9d", w=0)
    A.alu_ri("cmp", "r9d", 0x40, "Q014 cmp r9d,64 (не больше 64 Б)")
    A.jcc("be", "hb_pair", "Q014 jbe hb_pair")
    A.jmp("hb_bad", "Q014 jmp hb_bad (блоб длиннее 64 Б)")
    A.label("hb_end")
    A.test_rr("r9d", "r9d", "Q014 test r9d,r9d", w=0)
    A.jcc("e", "hb_bad", "Q014 jz hb_bad (пустой блоб)")
    A.mov_rr("rax", "r9", "Q014 mov eax,r9d (длина)", w=0)
    A.ret("Q014 ret")
    A.label("hb_bad")
    A.mov_ri("rax", -1, "Q014 mov rax,-1")
    A.ret("Q014 ret")

    # ---------------------------------------------- K0-Q015 do_pev2
    A.label("do_pev2")
    A.cmp_rip_i8("sawpev2", 0, "Q015 cmp dword [rip+sawpev2],0")
    A.jcc("ne", "dp_bad", "Q015 jne dp_bad (повтор !pev2)")
    A.call("skip_spaces", "Q015 call skip_spaces")
    A.call("read_hexv", "Q015 call read_hexv (H)")
    A.alu_ri("cmp", "rax", -1, "Q015 cmp rax,-1")
    A.jcc("e", "dp_bad", "Q015 jz dp_bad")
    A.alu_ri("cmp", "eax", 0x40, "Q015 cmp eax,0x40 (H >= 0x40)")
    A.jcc("b", "dp_bad", "Q015 jb dp_bad (H меньше DOS-заголовка)")
    A.alu_ri("cmp", "eax", OUTLIM, "Q015 cmp eax,0x40000 (предел outbuf)")
    A.jcc("a", "dp_bad", "Q015 ja dp_bad (H больше outbuf — предел)")
    A.mov_rip("eax", "v2h", "Q015 mov [rip+v2h],eax", w=0, store=True)
    A.mov_rip_i32("sawpev2", 1, "Q015 mov dword [rip+sawpev2],1")
    A.call("expect_eol", "Q015 call expect_eol")
    A.test_rr("rax", "rax", "Q015 test rax,rax")
    A.jcc("ne", "dp_bad", "Q015 jnz dp_bad")
    A.alu_rr("xor", "eax", "eax", "Q015 xor eax,eax", w=0)
    A.ret("Q015 ret")
    A.label("dp_bad")
    A.mov_ri("eax", 1, "Q015 mov eax,1")
    A.ret("Q015 ret")

    # ---------------------------------------------- K0-Q016 do_hdr
    A.label("do_hdr")
    A.call("skip_spaces", "Q016 call skip_spaces")
    A.call("read_hexv", "Q016 call read_hexv (off)")
    A.alu_ri("cmp", "rax", -1, "Q016 cmp rax,-1")
    A.jcc_near("e", "dh_bad", "Q016 jz dh_bad")
    A.mov_rr("r12", "rax", "Q016 mov r12,rax (off)")
    A.cmp_r_rip("r12d", "v2h", "Q016 cmp r12d,[rip+v2h]", w=0)
    A.jcc_near("ae", "dh_bad", "Q016 jae dh_bad (off >= H — за границами)")
    A.lea_rip("rdi", "outbuf", "Q016 lea rdi,[rip+outbuf]")
    A.alu_rr("add", "rdi", "r12", "Q016 add rdi,r12 (outbuf+off)")
    A.lea_rip("r8", "outbuf", "Q016 lea r8,[rip+outbuf]")
    A.mov_rip("eax", "v2h", "Q016 mov eax,[rip+v2h]", w=0)
    A.alu_rr("add", "r8", "rax", "Q016 add r8,rax (предел = outbuf+H)")
    A.call("skip_spaces", "Q016 call skip_spaces (перед блобом)")
    A.call("hex_blob", "Q016 call hex_blob (блоб -> outbuf+off)")
    A.alu_ri("cmp", "rax", -1, "Q016 cmp rax,-1")
    A.jcc_near("e", "dh_bad", "Q016 jz dh_bad")
    A.mov_rr("r13", "rax", "Q016 mov r13,rax (длина)")
    A.mov_rip("ecx", "spancnt", "Q016 mov ecx,[rip+spancnt]", w=0)
    A.alu_ri("cmp", "ecx", SPANMAX, "Q016 cmp ecx,64 (предел спанов)")
    A.jcc_near("ae", "dh_bad", "Q016 jae dh_bad")
    A.lea_rip("r10", "spantab", "Q016 lea r10,[rip+spantab]")
    A.alu_rr("xor", "r8d", "r8d", "Q016 xor r8d,r8d (j)", w=0)
    A.label("dhl_loop")
    A.cmp_r_rip("r8d", "spancnt", "Q016 cmp r8d,[rip+spancnt]", w=0)
    A.jcc("ae", "dhl_ins", "Q016 jae dhl_ins")
    A.mov_mr("eax", "r10", None, "Q016 mov eax,[r10] (start_j)", w=0)
    A.mov_mr("edx", "r10", 4, "Q016 mov edx,[r10+4] (end_j)", w=0)
    A.alu_rr("cmp", "r12d", "edx", "Q016 cmp r12d,edx (off vs end_j)", w=0)
    A.jcc("ae", "dhl_next", "Q016 jae dhl_next")
    A.alu_rr("cmp", "eax", "r13d", "Q016 cmp eax,r13d (start_j vs off+len)", w=0)
    A.jcc("ae", "dhl_next", "Q016 jae dhl_next")
    A.jmp("dh_bad", "Q016 jmp dh_bad (наложение патчей)", short=False)
    A.label("dhl_next")
    A.alu_ri("add", "r10", 8, "Q016 add r10,8", w=1)
    A.inc("r8d", "Q016 inc r8d", w=0)
    A.jmp("dhl_loop", "Q016 jmp dhl_loop")
    A.label("dhl_ins")
    A.mov_rm("r10", None, "r12d", "Q016 mov [r10],r12d (off)", w=0)
    A.mov_rm("r10", 4, "r13d", "Q016 mov [r10+4],r13d (len)", w=0)
    A.inc("ecx", "Q016 inc ecx", w=0)
    A.mov_rip("ecx", "spancnt", "Q016 mov [rip+spancnt],ecx", w=0,
              store=True)
    A.call("expect_eol", "Q016 call expect_eol")
    A.test_rr("rax", "rax", "Q016 test rax,rax")
    A.jcc_near("ne", "dh_bad", "Q016 jnz dh_bad")
    A.alu_rr("xor", "eax", "eax", "Q016 xor eax,eax", w=0)
    A.ret("Q016 ret")
    A.label("dh_bad")
    A.mov_ri("eax", 1, "Q016 mov eax,1")
    A.ret("Q016 ret")

    # ---------------------------------------------- K0-Q017 do_body
    A.label("do_body")
    A.cmp_rip_i8("sawbody", 0, "Q017 cmp dword [rip+sawbody],0")
    A.jcc("ne", "db_bad", "Q017 jne db_bad (повтор !body)")
    A.call("skip_spaces", "Q017 call skip_spaces")
    A.call("read_hexv", "Q017 call read_hexv (n)")
    A.alu_ri("cmp", "rax", -1, "Q017 cmp rax,-1")
    A.jcc("e", "db_bad", "Q017 jz db_bad")
    A.mov_rip("eax", "bodyn", "Q017 mov [rip+bodyn],eax", w=0, store=True)
    A.mov_rip_i32("sawbody", 1, "Q017 mov dword [rip+sawbody],1")
    A.call("expect_eol", "Q017 call expect_eol")
    A.test_rr("rax", "rax", "Q017 test rax,rax")
    A.jcc("ne", "db_bad", "Q017 jnz db_bad")
    A.alu_rr("xor", "eax", "eax", "Q017 xor eax,eax", w=0)
    A.ret("Q017 ret")
    A.label("db_bad")
    A.mov_ri("eax", 1, "Q017 mov eax,1")
    A.ret("Q017 ret")

    # ---------------------------------------------- K0-Q018 do_sec
    A.label("do_sec")
    A.call("skip_spaces", "Q018 call skip_spaces (n)")
    A.call("read_hexv", "Q018 call read_hexv (n)")
    A.alu_ri("cmp", "rax", -1, "Q018 cmp rax,-1")
    A.jcc_near("e", "ds_bad", "Q018 jz ds_bad")
    A.mov_rr("r12", "rax", "Q018 mov r12,rax (n)")
    A.call("skip_spaces", "Q018 call skip_spaces (off)")
    A.call("read_hexv", "Q018 call read_hexv (off)")
    A.alu_ri("cmp", "rax", -1, "Q018 cmp rax,-1")
    A.jcc_near("e", "ds_bad", "Q018 jz ds_bad")
    A.mov_rr("r13", "rax", "Q018 mov r13,rax (off)")
    A.lea_rip("rdi", "secdata", "Q018 lea rdi,[rip+secdata]")
    A.mov_rip("eax", "secdpos", "Q018 mov eax,[rip+secdpos]", w=0)
    A.alu_rr("add", "rdi", "rax", "Q018 add rdi,rax (secdata+pos)")
    A.lea_rip("r8", "secdata", "Q018 lea r8,[rip+secdata]")
    A.alu_ri("add", "r8", SECLEN, "Q018 add r8,0x2000 (предел)", w=1)
    A.call("skip_spaces", "Q018 call skip_spaces (перед блобом)")
    A.call("hex_blob", "Q018 call hex_blob (блоб -> secdata)")
    A.alu_ri("cmp", "rax", -1, "Q018 cmp rax,-1")
    A.jcc_near("e", "ds_bad", "Q018 jz ds_bad")
    A.mov_rr("r14", "rax", "Q018 mov r14,rax (длина)")
    A.mov_rip("ecx", "secnt", "Q018 mov ecx,[rip+secnt]", w=0)
    A.alu_ri("cmp", "ecx", SECMAX, "Q018 cmp ecx,128 (предел записей)")
    A.jcc_near("ae", "ds_bad", "Q018 jae ds_bad")
    A.lea_rip("r10", "sectab", "Q018 lea r10,[rip+sectab]")
    A.alu_rr("xor", "r8d", "r8d", "Q018 xor r8d,r8d (j)", w=0)
    A.label("dsl_loop")
    A.cmp_r_rip("r8d", "secnt", "Q018 cmp r8d,[rip+secnt]", w=0)
    A.jcc("ae", "dsl_ins", "Q018 jae dsl_ins")
    A.mov_mr("eax", "r10", None, "Q018 mov eax,[r10] (n_j)", w=0)
    A.alu_rr("cmp", "eax", "r12d", "Q018 cmp eax,r12d (та же секция?)", w=0)
    A.jcc("ne", "dsl_next", "Q018 jne dsl_next (другая секция)")
    A.mov_mr("eax", "r10", 4, "Q018 mov eax,[r10+4] (off_j)", w=0)
    A.mov_mr("edx", "r10", 12, "Q018 mov edx,[r10+12] (len_j)", w=0)
    A.alu_rr("add", "edx", "eax", "Q018 add edx,eax (end_j)", w=0)
    A.alu_rr("cmp", "r13d", "edx", "Q018 cmp r13d,edx (off vs end_j)", w=0)
    A.jcc("ae", "dsl_next", "Q018 jae dsl_next")
    A.mov_rr("edx", "r14", "Q018 mov edx,r14d (len)", w=0)
    A.alu_rr("add", "edx", "r13d", "Q018 add edx,r13d (off+len)", w=0)
    A.alu_rr("cmp", "eax", "edx", "Q018 cmp eax,edx (off_j vs off+len)", w=0)
    A.jcc("ae", "dsl_next", "Q018 jae dsl_next")
    A.jmp("ds_bad", "Q018 jmp ds_bad (наложение !sec)", short=False)
    A.label("dsl_next")
    A.alu_ri("add", "r10", 16, "Q018 add r10,16", w=1)
    A.inc("r8d", "Q018 inc r8d", w=0)
    A.jmp("dsl_loop", "Q018 jmp dsl_loop")
    A.label("dsl_ins")
    A.mov_rm("r10", None, "r12d", "Q018 mov [r10],r12d (n)", w=0)
    A.mov_rm("r10", 4, "r13d", "Q018 mov [r10+4],r13d (off)", w=0)
    A.mov_rip("eax", "secdpos", "Q018 mov eax,[rip+secdpos]", w=0)
    A.mov_rm("r10", 8, "eax", "Q018 mov [r10+8],eax (datapos)", w=0)
    A.mov_rm("r10", 12, "r14d", "Q018 mov [r10+12],r14d (len)", w=0)
    A.alu_rr("add", "eax", "r14", "Q018 add eax,r14d", w=0)
    A.mov_rip("eax", "secdpos", "Q018 mov [rip+secdpos],eax", w=0,
              store=True)
    A.inc("ecx", "Q018 inc ecx", w=0)
    A.mov_rip("ecx", "secnt", "Q018 mov [rip+secnt],ecx", w=0, store=True)
    A.call("expect_eol", "Q018 call expect_eol")
    A.test_rr("rax", "rax", "Q018 test rax,rax")
    A.jcc_near("ne", "ds_bad", "Q018 jnz ds_bad")
    A.alu_rr("xor", "eax", "eax", "Q018 xor eax,eax", w=0)
    A.ret("Q018 ret")
    A.label("ds_bad")
    A.mov_ri("eax", 1, "Q018 mov eax,1")
    A.ret("Q018 ret")

