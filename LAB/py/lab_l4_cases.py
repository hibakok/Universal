"""lab_l4_cases.py — якоря оракула библиотеки L4 (SPEC/14, LIB-1).

Вход:  — (константы-литералы).
Выход: корпуса якорей для секции 16 батареи (lab_t_l4.py):
         DEC — десятичная запись u64 (края разрядов);
         I64 — знаковая запись (дополнение до двух, края);
         REV — цифры в реверс-порядке буфера u64_to_dec_rev;
         STR — строки байтов до ПЕРВОГО NUL;
         BUF — буферы в прямом/обратном порядке;
         CPY/FILL — эффекты mem_copy/mem_fill на малой RAM
         (вкл. перекрытия обоих направлений — формула SPEC/14 п. 4);
         CMP_U64/CMP_I64 — композиция «печать числа + CRLF»
         (консоль-протокол составных кирпичей).
Функция: свидетель №2 («якоря»): литералы выписаны ВРУЧНУЮ по
         SPEC/14 п. 4 и НЕ вычисляются алгоритмом оракула
         (прецедент ANCHORS в lab_t_vm_corpus.py). Расхождение
         оракула с якорем = дефект оракула (чинить оракул, не якорь).
"""
CRLF = b"\r\n"

# u64 -> десятичная запись (print_u64; края разрядов и степени двойки)
DEC = [
    (0, "0"),
    (1, "1"),
    (9, "9"),
    (10, "10"),
    (99, "99"),
    (100, "100"),
    (1000, "1000"),
    (123456789, "123456789"),
    (4294967295, "4294967295"),            # 2^32 - 1
    (4294967296, "4294967296"),            # 2^32
    (9223372036854775807, "9223372036854775807"),    # 2^63 - 1
    (9223372036854775808, "9223372036854775808"),    # 2^63
    (18446744073709551615, "18446744073709551615"),  # 2^64 - 1
]

# u64 (дополнение до двух) -> знаковая запись (print_i64)
I64 = [
    (0, "0"),
    (1, "1"),
    (9223372036854775807, "9223372036854775807"),    # +2^63 - 1
    (9223372036854775808, "-9223372036854775808"),   # -2^63 (край)
    (18446744073709551606, "-10"),                   # -10
    (18446744073709551615, "-1"),                    # -1
]

# u64 -> (цифры реверс-порядка buf[0]=единицы, длина) — u64_to_dec_rev
REV = [
    (0, "0", 1),
    (1, "1", 1),
    (10, "01", 2),
    (12345, "54321", 5),
    (4294967295, "5927694924", 10),
    (18446744073709551615, "51615590737044764481", 20),
]

# байты (с NUL) -> строка до ПЕРВОГО нуля: (полные байты, вывод, длина)
STR = [
    (b"U-L4-OK\x00XX", "U-L4-OK", 7),
    (b"\x00AB", "", 0),
    (b"AB\x00CD\x00", "AB", 2),              # хвост после NUL не виден
    (b"U-L4-OK 61\r\n\x00", "U-L4-OK 61\r\n", 12),
    (b"1234567890", "1234567890", 10),       # NUL нет вовсе — вся строка
]

# буфер -> (прямой порядок, обратный): buf_out / buf_out_rev
BUF = [
    (b"12345", "12345", "54321"),
    (b"", "", ""),
    (b"U-L4-OK", "U-L4-OK", "KO-4L-U"),
    (b"A", "A", "A"),
    (b"010", "010", "010"),                  # палиндром
]

# mem_copy: (исходная RAM, dst, src, n, ожидаемая RAM)
# формула SPEC/14 п. 4: i = 0..n-1, RAM[dst+i] := RAM[src+i] (по возрастанию)
CPY = [
    (b"12345678", 4, 0, 4, b"12341234"),     # без перекрытия
    (b"ABCDEF", 1, 0, 3, b"AAAAEF"),         # перекрытие ВПЕРЁД: источник
    #                                          затирается до прочтения
    (b"ABCDEF", 0, 2, 3, b"CDEDEF"),         # перекрытие НАЗАД: без
    #                                          затирания источника
    (b"ABCDEF", 0, 0, 6, b"ABCDEF"),         # копия сам на себя
    (b"ABCDEF", 3, 1, 0, b"ABCDEF"),         # n = 0 — нет эффекта
    (b"00112233", 6, 4, 2, b"00112222"),     # хвост: байты src «22»
]

# mem_fill: (исходная RAM, dst, байт r2, n, ожидаемая RAM)
FILL = [
    (b"........", 2, 0x41, 3, b"..AAA..."),
    (b"........", 0, 0x00, 8, b"\x00" * 8),
    (b"ABCDEF", 3, 0x2E, 0, b"ABCDEF"),      # n = 0 — нет эффекта
    (b"ABCDEF", 0, 0x141, 3, b"AAADEF"),     # r2 AND 255: 0x141 -> 0x41
]

# композиция консоль-протокола: печать числа + crlf_out (значение, вывод)
CMP_U64 = [
    (0, "0\r\n"),
    (123, "123\r\n"),
    (18446744073709551615, "18446744073709551615\r\n"),
]
CMP_I64 = [
    (9223372036854775808, "-9223372036854775808\r\n"),   # i64-край
    (18446744073709551606, "-10\r\n"),                   # -10
]
