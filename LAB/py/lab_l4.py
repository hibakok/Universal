"""lab_l4.py — оракул библиотеки L4 (SPEC/14, слой LIB-1: числа и строки).

Вход:  аргументы кирпича LIB-1 — значение u64 (регистр), байты буфера/
         строки, адреса/длины RAM-операций.
Выход: наблюдаемый эффект кирпича — консоль (bytes) и/или RAM
         (bytearray) и/или буфер цифр (bytes, реверс-порядок) —
         точно по контрактам SPEC/14 п. 4.
Функция: эталонная семантика кирпичей библиотеки L4 (свидетель
         №1 — «сначала истина семантики», прецедент E7.1/E6.4a:
         реализация .uva (срезы E8.2+) обязана совпасть с этим
         оракулом на корпусе якорей lab_l4_cases.py; якоря —
         свидетель №2, ручные литералы). Оракул НЕ эмулирует UNIVM
         (это делает lab_vm.py): он моделирует НАБЛЮДАЕМЫЙ результат
         каждого кирпича по SPEC/14: консоль, RAM, буфер цифр.

Регистровая конвенция (SPEC/14 п. 3) здесь не видна: оракул
принимает ЗНАЧЕНИЯ аргументов (r1..r4) как параметры функций
и возвращает ЗНАЧЕНИЕ r1/эффекты — контракт карточки, не код.
"""
M64 = (1 << 64) - 1
TWO63 = 1 << 63
CRLF = b"\r\n"


# --- ветвь C: консоль (SPEC/14 п. 4) --------------------------------

def chr_out(byte):
    """K4-C001: консоль += r1 AND 255."""
    return bytes([byte & 0xFF])


def crlf_out():
    """K4-C002: консоль += 0D 0A."""
    return CRLF


def buf_out(buf):
    """K4-C003: консоль += RAM[addr..addr+len) — прямой порядок."""
    return bytes(buf)


def buf_out_rev(buf):
    """K4-C004: консоль += буфер в обратном порядке (addr+len-1..addr)."""
    return bytes(buf[::-1])


# --- ветвь N: числа (десятичная запись u64/i64) ----------------------

def u64_to_dec_rev(value):
    """K4-N001: r1=len; RAM[buf..buf+len) = цифры ASCII, buf[0]=единицы.

    Возвращает (digits_rev, length): digits_rev — байты цифр от МЛАДШЕЙ
    к старшей (rev-порядок буфера), length >= 1; value=0 -> (b"0", 1).
    """
    s = str(value & M64)            # десятичная запись u64, старшая слева
    return s[::-1].encode("ascii"), len(s)


def print_u64(value):
    """K4-N002: консоль += десятичная запись u64 (старшая слева)."""
    return str(value & M64).encode("ascii")


def print_i64(value):
    """K4-N003: консоль += знаковая запись (дополнение до двух).

    v < 2^63 -> цифры v; v >= 2^63 -> "-" + цифры (2^64 - v).
    """
    v = value & M64
    if v < TWO63:
        return str(v).encode("ascii")
    return b"-" + str((1 << 64) - v).encode("ascii")


# --- ветвь S: строки (байты до NUL) -----------------------------------

def str_len(data):
    """K4-S001: r1 = число байтов до первого 0 (не включая его)."""
    return data.index(0) if 0 in data else len(data)


def str_out(data):
    """K4-S002: консоль += байты до первого 0 (не включая его)."""
    return data[:str_len(data)]


# --- ветвь M: память (блочные операции) ------------------------------

def mem_copy(ram, dst, src, n):
    """K4-M001: RAM[dst+i] := RAM[src+i], i = 0..n-1 (по возрастанию).

    ram — bytearray (копия вызывающего не нужна: оракул возвращает
    изменённый буфер); формула задаёт поведение при перекрытии —
    каждый байт источника читается до записи в ту же ячейку.
    """
    for i in range(n):
        ram[dst + i] = ram[src + i]
    return ram


def mem_fill(ram, dst, byte, n):
    """K4-M002: RAM[dst..dst+n) := r2 AND 255."""
    b = byte & 0xFF
    for i in range(n):
        ram[dst + i] = b
    return ram
